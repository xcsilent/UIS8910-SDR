int rf_core_apply_mode(const struct rf_core_mode_bus *bus, uint32_t mode)
{
    static const uint16_t control[6] = {0x24,0x35,0x45,0x55,0x6d,0x7d};
    uint32_t word4, flag, word0=0;
    if (!bus || !bus->read || !bus->write || mode>=6u) return -1;
    if (bus->read(bus->context,0x32004u,2,&word4) ||
        bus->read(bus->context,0xb52au,2,&flag)) return -2;
    if ((flag&65535u)==1u) {
        if (bus->read(bus->context,0x32000u,2,&word0) ||
            bus->read(bus->context,0x32004u,2,&word4)) return -2;
        word0 &= 0xff00u;
        word4 &= 0x3fau;
    }
    uint32_t mode_control=control[mode],selector;
    if(mode==4u || mode==5u) {
        if(bus->read(bus->context,0xb538u,2,&selector))return -2;
        selector&=65535u;
        if(selector==5u || selector==15u)mode_control-=2u;
    }
    if (bus->write(bus->context,0x32000u,2,word0|mode_control) ||
        bus->write(bus->context,0x32004u,2,(word4|0x2c5u)&65535u)) return -2;
    uint32_t correction_index=0;
    static const uint16_t mode0_nco[4][2] = {
        {0x5555,0x0017},{0xaaab,0x00e8},{0,0},{0x5556,0x00e5}
    };
    for (unsigned i=0;i<43u;++i) {
        uint32_t value=configuration[mode][i];
        if(mode==0u && (i==26u || i==27u)) {
            if(bus->read(bus->context,0xb550u,2,&correction_index))return -2;
            correction_index&=65535u;
            if(correction_index>=4u)return -1;
        }
        if(mode==0u && (i==26u || i==27u))value=mode0_nco[correction_index][i-26u];
        if (bus->write(bus->context,0x32000u+offsets[i],2,value))
            return -2;
    }
    return 0;
}
